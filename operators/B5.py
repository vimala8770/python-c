
# Initialize variables
p = 12
q = 10

# Print binary representations
print(bin(p), bin(q))

# Bitwise operations
print(p & q)    # AND
print(p | q)    # OR
print(p ^ q)    # XOR
print(~p)       # NOT
print(p << 2)   # Left Shift
print(p >> 2)   # Right Shift
